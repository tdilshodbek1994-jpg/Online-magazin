export function errText(e: any): string {
  const code = String(e?.code ?? '');
  if (TEXT[code]) return TEXT[code];
  if (code.endsWith('_NOT_FOUND')) return 'Topilmadi.';
  if (code.endsWith('_INVALID_TRANSITION')) return 'Bu holatga o‘tkazib bo‘lmaydi.';
  const status = Number(e?.status ?? 0);
  if (status === 401) return TEXT.UNAUTHENTICATED;
  if (status === 403) return TEXT.FORBIDDEN;
  if (status === 429) return TEXT.RATE_LIMITED;
  if (e?.field_errors && Object.keys(e.field_errors).length) return TEXT.VALIDATION_FAILED;
  return code ? `Xatolik yuz berdi (${code}). Qayta urinib ko‘ring.` : 'Xatolik yuz berdi. Qayta urinib ko‘ring.';
}

